// ============================================================================
// Generator: knowledge/ksa/*.md frontmatter → lib/ai/personas/ksa-entries.ts
// Run: node scripts/gen-ksa-entries.mjs
//
// The selector (lib/ai/personas/ksa-encyclopedia.ts) must be PURE (no I/O per
// spec §2), so the pack frontmatter is baked into a committed const. This keeps a
// SINGLE SOURCE (the .md files) with a generated, in-sync artifact; the selector
// test re-parses the pack and asserts the const matches (drift guard).
//
// `injectSummary` is intentionally null for every entry until the Khalid window's
// curation pack-PR adds the `inject_summary` frontmatter (WO-ENCYCLOPEDIA render
// half is built on top of main once that lands). Nothing here fabricates it.
// ============================================================================
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const PACK_DIR = join(process.cwd(), "knowledge", "ksa");
const OUT = join(process.cwd(), "lib", "ai", "personas", "ksa-entries.ts");

/** Parse the leading `---` frontmatter block into a flat key→raw-string map. */
export function parseFrontmatter(md) {
  const m = md.match(/^---\n([\s\S]*?)\n---/);
  if (!m) return {};
  const out = {};
  for (const line of m[1].split("\n")) {
    const kv = line.match(/^([a-z_]+):\s*(.*)$/i);
    if (kv) out[kv[1]] = kv[2];
  }
  return out;
}

/** `[a, b, c]` → ["a","b","c"]; bare/quoted scalar → trimmed unquoted string. */
function arr(raw) {
  if (!raw) return [];
  const inner = raw.trim().replace(/^\[/, "").replace(/\]$/, "");
  return inner.split(",").map((s) => s.trim()).filter(Boolean);
}
function str(raw) {
  if (raw == null) return "";
  return raw.trim().replace(/^"(.*)"$/, "$1").replace(/^'(.*)'$/, "$1");
}

export function entryFromFrontmatter(fm) {
  return {
    id: str(fm.id),
    nameAr: str(fm.name_ar),
    nameEn: str(fm.name_en),
    category: str(fm.category),
    cuisineTags: arr(fm.cuisine_tags),
    regions: arr(fm.regions),
    menuJoinHint: str(fm.menu_join_hint),
    // null until the curation pack-PR adds inject_summary (never fabricated here).
    injectSummary: fm.inject_summary != null ? str(fm.inject_summary) : null,
  };
}

export function buildEntries() {
  const files = readdirSync(PACK_DIR)
    .filter((f) => f.endsWith(".md") && f.toLowerCase() !== "readme.md")
    .sort();
  return files.map((f) => entryFromFrontmatter(parseFrontmatter(readFileSync(join(PACK_DIR, f), "utf8"))));
}

// Only emit the file when run directly (the test imports the parsers above).
if (import.meta.url === `file://${process.argv[1]}`) {
  const entries = buildEntries();
  const body = `// GENERATED by scripts/gen-ksa-entries.mjs from knowledge/ksa/*.md — DO NOT EDIT BY HAND.
// Regenerate after any pack frontmatter change (e.g. the curation inject_summary PR):
//   node scripts/gen-ksa-entries.mjs
// The selector test (scripts/proof-ksa-encyclopedia.test.ts) re-parses the pack and
// asserts this stays in sync, so drift fails CI.

export interface KsaEntry {
  id: string;
  nameAr: string;
  nameEn: string;
  category: string;
  cuisineTags: string[];
  regions: string[];
  menuJoinHint: string;
  /** ≤160-char curated culture line; NULL until the curation pack-PR lands. */
  injectSummary: string | null;
}

export const KSA_ENTRIES: readonly KsaEntry[] = ${JSON.stringify(entries, null, 2)} as const;
`;
  writeFileSync(OUT, body);
  console.log(`wrote ${entries.length} entries → ${OUT}`);
}
